/** 효력시험: 질환 모델 이름을 넣어 만든다 */
function pdGuide(t: DocTest): TestGuide {
  const model = t.kd?.pd?.model || t.item;
  return {
    key: `pd:${model}`,
    name: `효력시험 (${model})`,
    what: `${model} 모델 동물에 시험물질을 투여해 질환 지표가 나아지는지 확인합니다. 정상군, 부형제군, 양성대조군과 비교합니다.`,
    why: "후보물질 선별, 유효 용량 탐색, 임상시험계획·허가 자료의 약리 근거로 쓰입니다.",
    looks: t.kd?.pd?.endpoints.length ? t.kd.pd.endpoints.slice(0, 5) : ["질환 지표", "체중", "조직병리 소견"],
    basis: "기관 표준작업지침(SOP), ICH M3(R2) 약력학 시험",
  };
}

/** 시험 하나의 안내. 맞는 규칙이 없으면 null (임상병리·조직병리 같은 개별 분석, 직접 적은 시험) */
export function guideFor(t: DocTest): TestGuide | null {
  if (testKind(t) === "pd") return pdGuide(t);
  const cat = t.category, item = t.item;
  if (!cat) return null;
  const hit = RULES.find((r) => (!r.cat || r.cat.test(cat)) && (!r.item || r.item.test(item)));
  return hit ? hit.g : null;
}

/** 견적서의 안내 목록. 같은 안내는 한 번만, 해당 시험 번호(1부터)를 모은다 */
export function docGuides(d: DocData): { g: TestGuide; nos: number[] }[] {
  const out = new Map<string, { g: TestGuide; nos: number[] }>();
  d.tests.forEach((t, i) => {
    const g = guideFor(t);
    if (!g) return;
    const cur = out.get(g.key);
    if (cur) cur.nos.push(i + 1);
    else out.set(g.key, { g, nos: [i + 1] });
  });
  return [...out.values()];
}

